def rodar(verboso=False):
    import server  # importa aqui: o servidor carrega o índice de apps do disco
    erros = 0
    for frase, esperado, *assunto in FRASES:
        obtido = server.rota_de(frase, assunto=assunto[0] if assunto else None)
        ok = any(e.lower() in obtido.lower() for e in esperado.split("|"))
        erros += not ok
        if verboso or not ok:
            print(f"{'ok  ' if ok else 'ERRO'}  {frase:48} → {obtido}" + ("" if ok else f"   (esperado: {esperado})"))
    for foco, frase, esperado in CONTEXTO:
        obtido = server.rota_de(frase, foco=foco)
        ok = any(e.lower() in obtido.lower() for e in esperado.split("|"))
        erros += not ok
        if verboso or not ok:
            print(f"{'ok  ' if ok else 'ERRO'}  [{foco}] {frase:40} → {obtido}" + ("" if ok else f"   (esperado: {esperado})"))
    for frase, esperado in PRONUNCIA:
        obtido = server.pronuncia(frase)
        ok = obtido == esperado
        erros += not ok
        if verboso or not ok:
            print(f"{'ok  ' if ok else 'ERRO'}  fala: {frase:42} → {obtido}" + ("" if ok else f"   (esperado: {esperado})"))
    total = len(FRASES) + len(CONTEXTO) + len(PRONUNCIA)
    print(f"\n{total - erros}/{total} certas ({(total - erros) / total:.0%})")
    return erros


